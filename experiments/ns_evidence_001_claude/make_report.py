#!/usr/bin/env python3
"""Render REPORT.md from outputs/results.json and outputs/comparison_vs_oai.json.

Every number in the tables is read from those files; only the narrative is typed.
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "outputs")
res = json.load(open(os.path.join(OUT, "results.json")))
cases, derived, meta = res["cases"], res["derived"], res["meta"]
cmp_rows = json.load(open(os.path.join(OUT, "comparison_vs_oai.json")))
oai = json.load(open(os.path.join(OUT, "oai_ns_evidence_001_results.json")))


def g(x, p=15):
    return ("%." + str(p) + "g") % x


def e(x):
    return "%.2e" % x


def pick(d, N, T, dt, form="convective"):
    return cases["%dD_N%d_T%g_dt%g_%s" % (d, N, T, dt, form)]


L = []
w = L.append

w("# NS-EVIDENCE-001 - independent verification (Claude bench)")
w("")
w("**Status:** independent numerical verification exercise. This report makes **no claim of global regularity, "
  "blow-up, or a solution of the Clay problem.** All runs are smooth, low-mode, periodic, finite-time cases.")
w("")
w("Generated by `make_report.py` from `outputs/results.json` and `outputs/comparison_vs_oai.json`; "
  "the numbers below are copied from those files by code, not typed.")
w("")
w("## 1. Method (derived and implemented from the equations)")
w("")
w("Unforced incompressible Navier-Stokes on the periodic box [0, 2pi)^d, nu = 0.01:")
w("`u_t + (u . grad)u = -grad p + nu Lap(u)`, `div u = 0`. Taking the Leray projector "
  "`P = I - k k^T/|k|^2` removes the pressure: `d/dt u_hat = -P F[(u . grad)u] - nu |k|^2 u_hat`.")
w("")
w("- **Space:** Fourier collocation on N^d nodes; 2/3-rule dealiasing per direction (keep `|k_i| <= floor(N/3)`).")
w("- **Time:** Lawson integrating-factor RK4 (viscous term exact, nonlinear term by RK4 stages).")
w("- **Precision / dependencies:** float64 / complex128; Python %s, NumPy %s (`numpy.fft`), single process, "
  "no other dependency. Machine: %s, %s CPUs." % (meta["python"], meta["numpy"], meta["platform"], meta["cpu_count"]))
w("- **Nonlinear term:** convective form by default. The rotational form `omega x u` is implemented as an independent "
  "cross-check (it differs by a gradient that `P` removes).")
w("- **Initial data:** 2D `u = (sin x cos y, -cos x sin y)`; 3D `u = (sin x cos y cos z, -cos x sin y cos z, 0)`.")
w("")
w("Diagnostics are volume averages over the box (divide the domain integral by (2pi)^d): "
  "`E = 1/2<|u|^2>`, `eps = nu<|grad u|^2>`, `Omega = 1/2<|omega|^2>` (from the curl of `u_hat`), "
  "`D = int_0^T eps dt`, `maxdiv = max |div u|` (spectral), balance residual `E(T) - E(0) + D(T)` (ideally 0). "
  "`D` is accumulated with the same RK4 stage values as the flow, so it is a fourth-order quadrature; a trapezoid "
  "estimate is also stored for comparison with the OpenAI report. Domain-integral values are in `results.json` "
  "(`*_integral`).")
w("")
w("Analytic `t = 0` values (volume averages): 2D `E=0.25, Omega=0.5, eps=0.01`; 3D `E=0.125, Omega=0.375, eps=0.0075`. "
  "Maximum absolute deviation of the solver from them: 2D %s, 3D %s."
  % (e(derived["t0_abs_error_max"]["2"]), e(derived["t0_abs_error_max"]["3"])))
w("")

w("## 2. Requested results, T = 0.1, dt = 0.001")
w("")
w("| d | N | E(0) | E(T) | eps(0) | eps(T) | integral of eps | Omega(0) | Omega(T) |")
w("|--:|--:|--:|--:|--:|--:|--:|--:|--:|")
prim = [pick(d, N, 0.1, 0.001) for d in (2, 3) for N in (16, 24, 32)]
for r in prim:
    w("| %d | %d | %s | %s | %s | %s | %s | %s | %s |" % (
        r["d"], r["N"], g(r["E0"]), g(r["E_T"]), g(r["eps0"]), g(r["eps_T"]), g(r["D_int"]), g(r["Omega0"]), g(r["Omega_T"])))
w("")
w("| d | N | max div (max over time) | balance residual (RK4-consistent) | runtime (s) |")
w("|--:|--:|--:|--:|--:|")
for r in prim:
    w("| %d | %d | %s | %s | %.2f |" % (r["d"], r["N"], e(r["maxdiv_max_over_time"]), e(r["resid_abs"]), r["runtime_s"]))
w("")
w("Runtimes include per-step diagnostics; they are not an accuracy metric.")
w("")
w("### 2D exact-solution error (`u = exp(-2 nu t) u(0)`)")
w("")
w("| N | max abs error | relative L2 error | abs error in E(T) | abs error in integral of eps | abs error in eps(T) |")
w("|--:|--:|--:|--:|--:|--:|")
for N in (16, 24, 32):
    r = pick(2, N, 0.1, 0.001)
    w("| %d | %s | %s | %s | %s | %s |" % (N, e(r["exact2d_max_abs_error"]), e(r["exact2d_l2_rel_error"]),
                                          e(r["exact2d_E_T_abs_error"]), e(r["exact2d_D_abs_error"]), e(r["exact2d_eps_T_abs_error"])))
w("")
w("The 2D Taylor-Green field is a single Fourier mode and the nonlinear term is a pure gradient, so the 2D case does "
  "**not** exercise the nonlinear term; it checks the viscous decay, projection, and bookkeeping only. "
  "Spatial spread across N is at roundoff (%s in E(T), %s in Omega(T))."
  % (e(derived["spatial_T0.1"]["2"]["E_T"]), e(derived["spatial_T0.1"]["2"]["Omega_T"])))
w("")

w("## 3. 3D temporal sensitivity, T = 0.5")
w("")
w("| N | dt | E(T) | integral of eps | Omega(T) | balance residual | runtime (s) |")
w("|--:|--:|--:|--:|--:|--:|--:|")
for N in (16, 24, 32):
    for dt in (0.004, 0.002, 0.001):
        r = pick(3, N, 0.5, dt)
        w("| %d | %g | %s | %s | %s | %s | %.1f |" % (N, dt, g(r["E_T"]), g(r["D_int"]), g(r["Omega_T"]), e(r["resid_abs"]), r["runtime_s"]))
w("")
w("Differences between dt = 0.004 and 0.001 are at the roundoff floor: "
  + "; ".join("N=%d: %s in E(T), %s in Omega(T)" % (
      N, e(abs(derived["temporal_T0.5"]["N%d" % N]["E_T"]["d_0p004_minus_0p001"])),
      e(abs(derived["temporal_T0.5"]["N%d" % N]["Omega_T"]["d_0p004_minus_0p001"]))) for N in (16, 24, 32))
  + ". Ratios of successive differences are therefore noise-dominated and are not used to claim an order.")
w("")
ot = derived["rk4_order_test_3D_N16_T0.5"]
w("### RK4 order test (added to resolve the above)")
w("")
w("3D, N = 16, T = 0.5; errors against the dt = 0.001 run of the same configuration.")
w("")
w("| dt | error in E(T) | error in Omega(T) | error in integral of eps |")
w("|--:|--:|--:|--:|")
for i, dt in enumerate(ot["Omega_T"]["dt"]):
    w("| %g | %s | %s | %s |" % (dt, e(ot["E_T"]["abs_error_vs_dt0p001"][i]), e(ot["Omega_T"]["abs_error_vs_dt0p001"][i]),
                                  e(ot["D_int"]["abs_error_vs_dt0p001"][i])))
w("")
w("Observed order (successive halvings): Omega(T) %s; integral of eps %s; E(T) %s (last value reaches the noise floor). "
  "This is the expected fourth order. Extrapolating the Omega(T) error to dt = 0.004 predicts about %s, "
  "matching the observed ~3e-14 scatter above."
  % ([round(o, 2) for o in ot["Omega_T"]["observed_order"]], [round(o, 2) for o in ot["D_int"]["observed_order"]],
     [round(o, 2) for o in ot["E_T"]["observed_order"]],
     e(ot["Omega_T"]["abs_error_vs_dt0p001"][0] * (0.004 / 0.1) ** 4)))
w("")

w("## 4. Extra checks (beyond the request)")
w("")
vs = derived["vs_N64_ref"]
w("**Spatial convergence against an N = 64 reference (3D, dt = 0.002 for the reference):**")
w("")
w("| case | E(T) diff | Omega(T) diff | eps(T) diff |")
w("|--|--:|--:|--:|")
for k in ("T0.1_N16_dt0.001", "T0.1_N24_dt0.001", "T0.1_N32_dt0.001", "T0.5_N16_dt0.002", "T0.5_N24_dt0.002", "T0.5_N32_dt0.002"):
    w("| %s | %s | %s | %s |" % (k, e(vs[k]["E_T"]), e(vs[k]["Omega_T"]), e(vs[k]["eps_T"])))
w("")
w("At T = 0.1 every resolution is converged to roundoff, so N = 16/24/32 at T = 0.1 cannot show spatial convergence. "
  "At T = 0.5, N = 16 is not fully resolved (Omega(T) off by %s), N = 24 is much closer (%s) and N = 32 is at "
  "roundoff (%s), the rapid decay expected for smooth data."
  % (e(abs(vs["T0.5_N16_dt0.002"]["Omega_T"])), e(abs(vs["T0.5_N24_dt0.002"]["Omega_T"])), e(abs(vs["T0.5_N32_dt0.002"]["Omega_T"]))))
w("")
w("**dt = 0.002 / 0.0005 versus 0.001 at T = 0.1, N = 32:** all differences <= %s (roundoff)."
  % e(max(abs(v) for blk in derived["dt_T0.1_N32"].values() for v in blk.values())))
w("")
fc = derived["form_check"]
w("**Convective versus rotational form (N = 32):** difference in every reported diagnostic is %s. "
  "Exactly zero is a rounding coincidence, not a disabled code path: `--selftest` compares the two nonlinear terms on a "
  "random divergence-free field and finds relative differences of about 4e-16 (2D and 3D), they differ at roundoff on "
  "Taylor-Green states, and they take different code paths (runtimes differ). The Taylor-Green trajectories differ by less "
  "than one unit in the last place of these diagnostics." % ("exactly 0.0" if all(v == 0.0 for b in fc.values() for v in b.values()) else "<= roundoff"))
w("")
req = [r for r in cases.values() if r["tag"] != "order_test"]  # order-test runs use deliberately large dt
w("**Energy balance** (all %d runs with dt <= 0.004, i.e. excluding the deliberately coarse order-test runs): "
  "the RK4-consistent residual `E(T)-E(0)+D(T)` is at most %s; with trapezoid quadrature it is up to %s "
  "(second-order quadrature error, see section 5). Maximum divergence over those runs and all times: %s. "
  "`eps` from `nu<|grad u|^2>` and `2 nu Omega` agree to %s. In the order-test runs the RK4-consistent residual falls from %s (dt = 0.1) "
  "to %s (dt = 0.00625)."
  % (len(req), e(max(abs(r["resid_abs"]) for r in req)),
     e(max(abs(r["resid_abs_trapezoid"]) for r in req)),
     e(max(r["maxdiv_max_over_time"] for r in req)),
     e(max(abs(r["eps_minus_2nuOmega_T"]) for r in req)),
     e(abs(pick(3, 16, 0.5, 0.1)["resid_abs"])), e(abs(pick(3, 16, 0.5, 0.00625)["resid_abs"]))))
w("")

w("## 5. Comparison with NS-EVIDENCE-001 (OpenAI bench, PR #130)")
w("")
w("Their JSON was copied verbatim from PR #130 head `1992c6532b2e1efead3f71a46afbd626e7a7cb28` into "
  "`outputs/oai_ns_evidence_001_results.json` (sha256 `8b193569192c8a1723810b514aa68d7016d24c6cb0cdab6ce8c08ae0a0f7fc23`). "
  "My results were committed (`1a54015`) **before** I read it. Afterwards I added two sets of runs, flagged in the source: "
  "the 2D dt = 0.002 configuration they used (so quadrature residuals compare like for like) and the RK4 order test. "
  "I did not read or run their source for this comparison.")
w("")
w("Maximum absolute difference between their reported values and mine, over all matched rows:")
w("")
agg = {}
for rec in cmp_rows:
    for k, v in rec.items():
        if k == "id" or v["openai"] is None:
            continue
        agg[k] = max(agg.get(k, 0.0), v["abs_diff"])
w("| quantity | max abs difference |")
w("|--|--:|")
for k, v in agg.items():
    w("| %s | %s |" % (k, e(v)))
w("")
w("**Result: no disagreement beyond roundoff on any physical quantity** (energy, enstrophy, dissipation rate, "
  "integrated dissipation, initial values). Items worth recording, none of them a failure:")
w("")
w("1. **Balance residual is a quadrature artifact, as their report says.** Their `-1.3e-11` (3D) and `-5.3e-13` (2D) are "
  "reproduced to ~1e-15 by my trapezoid variant (sign convention flipped: theirs is `E(0)-E(T)-trapz`). With RK4-consistent "
  "quadrature my residual is ~1e-16..1e-15, and it falls at about fourth order in dt (order test). Their temporal-sensitivity "
  "residuals (-9.72e-10, -2.43e-10, -6.08e-11 for dt = 0.004, 0.002, 0.001) fall by a factor of 4 per halving, i.e. they track "
  "the trapezoid rule, **not** the solver's temporal error.")
w("2. **Their dt-sensitivity check is below the roundoff floor.** Their E(T) at dt = 0.004/0.002/0.001 differs only at ~1e-14, "
  "so it does not test temporal convergence. The order test above, at larger dt, does.")
w("3. **N-scatter in their rows is larger than mine.** Spread across N = 16/24/32 in 3D E(T): theirs %s, mine %s; in Omega(T): "
  "theirs %s, mine %s. All are roundoff-scale. I did not investigate their source for the cause; a different operation order "
  "or normalisation in the FFT bookkeeping would be enough." % (
      e(max(c["energy_final"] for c in oai["cases"] if c["dimension"] == 3) - min(c["energy_final"] for c in oai["cases"] if c["dimension"] == 3)),
      e(derived["spatial_T0.1"]["3"]["E_T"]),
      e(max(c["enstrophy_final"] for c in oai["cases"] if c["dimension"] == 3) - min(c["enstrophy_final"] for c in oai["cases"] if c["dimension"] == 3)),
      e(derived["spatial_T0.1"]["3"]["Omega_T"])))
w("4. **2D exact error:** theirs 2.6e-15..1.2e-14, mine 1.0e-15..2.0e-15 at the same dt = 0.002 (both roundoff).")
w("5. **N = 16/24/32 at T = 0.1 is not a convergence study** (their report says as much); the N = 64 reference above shows "
  "genuine spatial convergence at T = 0.5. A consequence for their temporal-sensitivity block (3D, N = 16, T = 0.5): their E(T) "
  "(0.12127471447955) sits %s above the converged value, a **spatial truncation error** of N = 16, over a thousand times "
  "larger than the dt effect they were probing (~1e-14). It does not change their conclusion, but the dominant error in that "
  "block is spatial, not temporal." % e(oai["temporal_sensitivity_3d_n16_t05"][0]["energy_final"] - pick(3, 64, 0.5, 0.002)["E_T"]))
w("6. **Divergence near 1e-15 is a consistency check of the projection, not independent evidence of solution quality.**")
w("")

w("## 6. Limits of this verification")
w("")
w("- My solver and theirs are the same **family** of method (Fourier pseudo-spectral, 2/3 dealiasing, Leray projection, RK4). "
  "Agreement shows the implementations are consistent; it does not validate the method against a different discretisation. "
  "A second solver of another family (finite volume or lattice) remains outstanding.")
w("- The 2D case does not exercise the nonlinear term. The 3D case does, but only over a short, smooth, low-mode window. "
  "No manufactured-solution test with a forcing term, no higher-mode data, no turbulence or near-singular regime.")
w("- Nothing here bears on global regularity, blow-up, or the Clay problem.")
w("")
w("## 7. Reproduction and provenance")
w("")
w("```")
w("python3 -I ns_spectral.py --selftest")
w("python3 -I ns_spectral.py --tags primary,dt_check,temporal,form_check,reference,oai_match,order_test")
w("python3 -I compare_oai.py")
w("python3 -I make_report.py")
w("```")
w("")
w("- Source: `ns_spectral.py` (sha256 recorded in `outputs/results.json` meta: `%s`). The solver core (`PeriodicNS`, `run_case`) "
  "is unchanged since the first commit `1a54015`; later edits to this file are purely additive (`git diff 1a54015 -- ns_spectral.py` "
  "shows 38 insertions, in `build_cases`, `analyze` and the selftest), so the frozen results were not recomputed with different numerics." % meta["source_sha256"])
w("- Outputs: `outputs/results.json`, `outputs/histories/*.csv` (per-step E, eps, Omega, maxdiv, D), "
  "`outputs/comparison_vs_oai.json`, `outputs/oai_ns_evidence_001_results.json`.")
w("- Commits on branch `claude/ns-evidence-001-independent`: first freeze `1a5401539e14177e0ff079df7506efd34ce14b2a` "
  "(solver and primary/dt/temporal/form/reference results, before reading PR #130); the later commit(s) add the post-hoc "
  "runs, the comparison and this report. The final commit SHA is reported in the hand-off message, since a commit cannot contain its own SHA.")
w("")
w("Authored-by: Claude (Anthropic) - Architect bench")
w("")

with open(os.path.join(HERE, "REPORT.md"), "w") as fh:
    fh.write("\n".join(L))
print("wrote REPORT.md (%d lines)" % len(L))
